"""Writes contracts/connector-api.yaml: the connector's API plus the platform's /connector/v1 API,
one OpenAPI 3.1 document (python -m scripts.gen_contract, from connector/)."""

from pathlib import Path

import yaml

OUT = Path(__file__).resolve().parents[2] / "contracts" / "connector-api.yaml"

SIGNING = """Ed25519-signed request. Signed bytes: METHOD \\n PATH?QUERY \\n X-NC-Timestamp \\n X-NC-Nonce \\n
hex(SHA-256(body)). Headers: X-NC-Key (signer: "platform" or the hospital's site ID),
X-NC-Timestamp (unix seconds, within 300 s), X-NC-Nonce (16-64 chars, single use),
X-NC-Signature (base64url of the signature, no padding)."""


def build() -> dict:
    from app.main import app as platform_app

    from ncconnector.main import app as connector_app

    c = connector_app.openapi()
    p = platform_app.openapi()
    doc = {
        "openapi": "3.1.0",
        "info": {
            "title": "NeuroCapture hospital connector contract",
            "version": "1.0.0",
            "description": (
                "Connector API (served by the hospital connector) and the platform endpoints the connector "
                "calls. Patient identity (names, MRNs, contact details, records) only appears in responses "
                "of the connector to the hospital's own staff. "
                "Generated by connector/scripts/gen_contract.py."
            ),
        },
        "servers": [{"url": "https://connector.hospital.example", "description": "Hospital connector"}],
        "paths": {},
        "components": {
            "schemas": {},
            "securitySchemes": {
                "connectorToken": {
                    "type": "http",
                    "scheme": "bearer",
                    "bearerFormat": "JWT (EdDSA, aud site:<id>) from POST /hospital/connector-token",
                },
                "signedRequest": {
                    "type": "apiKey",
                    "in": "header",
                    "name": "X-NC-Signature",
                    "description": SIGNING,
                },
            },
        },
    }
    for path, item in c["paths"].items():
        doc["paths"][path] = item
    platform_server = [{"url": "https://api.neurocapture.example", "description": "NeuroCapture platform"}]
    for path, item in p["paths"].items():
        if path.startswith("/connector/v1") or path.startswith("/.well-known") or "connector" in path:
            doc["paths"][path] = {**item, "servers": platform_server}
    doc["components"]["schemas"].update(p["components"]["schemas"])
    doc["components"]["schemas"].update(c["components"]["schemas"])
    used = _refs(doc["paths"])
    while True:
        more = used | _refs(
            {k: doc["components"]["schemas"][k] for k in used if k in doc["components"]["schemas"]}
        )
        if more == used:
            break
        used = more
    doc["components"]["schemas"] = {
        k: v for k, v in sorted(doc["components"]["schemas"].items()) if k in used
    }
    return doc


def _refs(obj) -> set[str]:
    out: set[str] = set()
    if isinstance(obj, dict):
        ref = obj.get("$ref")
        if isinstance(ref, str) and ref.startswith("#/components/schemas/"):
            out.add(ref.rsplit("/", 1)[1])
        for v in obj.values():
            out |= _refs(v)
    elif isinstance(obj, list):
        for v in obj:
            out |= _refs(v)
    return out


if __name__ == "__main__":
    OUT.write_text(
        "# Generated: python -m scripts.gen_contract (connector/). Do not edit.\n"
        + yaml.safe_dump(build(), sort_keys=False, allow_unicode=True)
    )
    print(f"wrote {OUT}")  # noqa: T201
