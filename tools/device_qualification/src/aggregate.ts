import {
  validate,
  formatIssues,
  type BenchmarkReport,
  type DeviceTiersConfig,
} from '@neurocapture/contracts-ts';
import { assignTier, formatTierReason } from '@neurocapture/quality-core';

export interface DeviceRow {
  device: string;
  os: string;
  runs: number;
  tier: string;
  provisional: boolean;
  best60: string;
  best30: string;
  reasons: string;
}

/** Group reports by device + OS version and re-assess with the current tier config (never trust stored tiers). */
export function aggregate(
  files: { name: string; data: unknown }[],
  cfg: DeviceTiersConfig,
): { rows: DeviceRow[]; errors: string[] } {
  const errors: string[] = [];
  const groups = new Map<string, BenchmarkReport[]>();
  for (const f of files) {
    const res = validate('benchmark-report', f.data);
    if (!res.valid) {
      errors.push(formatIssues(f.name, res.issues));
      continue;
    }
    const r = f.data as BenchmarkReport;
    const key = `${r.device.manufacturer} ${r.device.model}|${r.device.osName} ${r.device.osVersion}`;
    groups.set(key, [...(groups.get(key) ?? []), r]);
  }
  const fmt = (rs: BenchmarkReport[], fps: number) => {
    const best = rs
      .filter((r) => r.settings.targetFps === fps)
      .sort((a, b) => b.recording.effectiveFps - a.recording.effectiveFps)[0];
    return best
      ? `${best.recording.effectiveFps.toFixed(1)} fps, ${(best.recording.droppedFrac * 100).toFixed(2)}% drop`
      : '—';
  };
  const rows = [...groups.entries()]
    .map(([key, rs]) => {
      const [device, os] = key.split('|') as [string, string];
      const a = assignTier(rs, cfg);
      return {
        device,
        os,
        runs: rs.length,
        tier: a.tier,
        provisional: a.provisional,
        best60: fmt(rs, 60),
        best30: fmt(rs, 30),
        reasons: a.reasons.map(formatTierReason).join('; '),
      };
    })
    .sort((x, y) => x.tier.localeCompare(y.tier) || x.device.localeCompare(y.device));
  return { rows, errors };
}

export function toMarkdown(rows: DeviceRow[], cfgVersion: string): string {
  const head = [
    '# Device qualification summary',
    '',
    `Generated by \`pnpm --filter @neurocapture/device-qualification summary\` with ${cfgVersion}. Do not edit by hand.`,
    '',
    '| Device | OS | Runs | Tier | 60 fps run | 30 fps run | Notes |',
    '|---|---|---|---|---|---|---|',
  ];
  const body = rows.map(
    (r) =>
      `| ${r.device} | ${r.os} | ${r.runs} | ${r.tier}${r.provisional ? ' (provisional)' : ''} | ${r.best60} | ${r.best30} | ${r.reasons || '—'} |`,
  );
  return [...head, ...(body.length ? body : ['| _no reports yet_ | | | | | | |']), ''].join('\n');
}
